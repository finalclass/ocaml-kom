module FlowCheckpoint = struct
  type t = {
    input : Message.t;
    results : (NodeResult.t) list;
    pending : (Work.t) list;
  }

  let make ~input ~results ~pending () =
    { input = input; results = results; pending = pending; }

  let encode_value (v : t) : (Drut_runtime.value, Cyrograf.Error.t) result =
    let open! Drut_runtime.Syntax in
    let* f0 = Drut_runtime.field "input" ((match Message.to_drut (v.input) with Ok text -> Drut_runtime.of_string text | Error _ as error -> error)) in
    let* f1 = Drut_runtime.field "results" (Drut_runtime.enc_list (fun x -> (match NodeResult.to_drut (x) with Ok text -> Drut_runtime.of_string text | Error _ as error -> error)) (v.results)) in
    let* f2 = Drut_runtime.field "pending" (Drut_runtime.enc_list (fun x -> (match Work.to_drut (x) with Ok text -> Drut_runtime.of_string text | Error _ as error -> error)) (v.pending)) in
    Ok (`List [f0; f1; f2])

  let decode_value (wire : Drut_runtime.value) : (t, Cyrograf.Error.t) result =
    let open! Drut_runtime.Syntax in
    let* arr = Drut_runtime.dec_struct 3 wire in
    let* input = Drut_runtime.field "input" (Message.from_drut (Drut_runtime.to_string (arr.(0)))) in
    let* results = Drut_runtime.field "results" (Drut_runtime.dec_list (fun x -> NodeResult.from_drut (Drut_runtime.to_string (x))) (arr.(1))) in
    let* pending = Drut_runtime.field "pending" (Drut_runtime.dec_list (fun x -> Work.from_drut (Drut_runtime.to_string (x))) (arr.(2))) in
    Ok { input = input; results = results; pending = pending; }

  let to_drut (v : t) : (string, Cyrograf.Error.t) result =
    match encode_value v with
    | Ok wire -> Ok (Drut_runtime.to_string wire)
    | Error _ as error -> error

  let from_drut (text : string) : (t, Cyrograf.Error.t) result =
    match Drut_runtime.of_string text with
    | Ok wire -> decode_value wire
    | Error _ as error -> error
end

