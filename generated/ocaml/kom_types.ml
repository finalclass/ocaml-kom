    | Completed payload ->
      let* p = (match MessageBatch.to_drut (payload) with Ok text -> Drut_runtime.of_string text | Error _ as error -> error) in
      Ok (`List [ `String "Completed"; p ])
    | Failed payload ->
      let* p = (match Problem.to_drut (payload) with Ok text -> Drut_runtime.of_string text | Error _ as error -> error) in
      Ok (`List [ `String "Failed"; p ])

  let decode_value (wire : Drut_runtime.value) : (t, Cyrograf.Error.t) result =
    let open! Drut_runtime.Syntax in
    match wire with
